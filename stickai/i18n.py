def set_language(lang: str) -> None:
    global _lang
    _lang = lang if lang in ("en", "ru", "sk") else "en"


def language() -> str:
    return _lang


def tr(key: str, **kw) -> str:
    entry = STRINGS.get(key)
    if entry is None:
        return key
    text = entry.get(_lang) or entry["en"]
    return text.format(**kw) if kw else text
